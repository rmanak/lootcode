"""Input-constraint validator for design problem 'adam-optimizer'.

The structural half was generated by scripts/generate_class_validators.py
(deterministic, from the class block in meta.json): aligned operations/args
lists, the constructor exactly once at the front, every later op a declared
method, and each arg list matching its op's arity and per-arg type.

The rest is hand-written (re-running the generator with --force regenerates the
structural part and drops it): 1 <= len(params) <= 50 with every param finite
and |param| <= 100; 0 < lr <= 1; 0 <= beta1 < 1 and 0 <= beta2 < 1;
1e-12 <= eps <= 1; every grad has exactly len(params) finite numbers with
|g| <= 1000; at most 200 step calls.
"""
import math


# op-name -> list of (base_type, list_dims) for each positional argument.
_SIG = {
    'Adam': [('float', 1), ('float', 0), ('float', 0), ('float', 0), ('float', 0)],
    'step': [('float', 1)],
}
_CTOR = 'Adam'


def _scalar_ok(v, base):
    if base == "int":
        return isinstance(v, int) and not isinstance(v, bool)
    if base in ("float", "num"):
        return isinstance(v, (int, float)) and not isinstance(v, bool)
    if base == "bool":
        return isinstance(v, bool)
    if base in ("string", "str", "char"):
        return isinstance(v, str)
    if base in ("TreeNode", "ListNode", "DoublyLinkedList"):
        # Wire form: a level-order / flat value list of ints (None marks a hole),
        # or None / [] for an empty structure.
        if v is None:
            return True
        if not isinstance(v, list):
            return False
        return all(x is None or (isinstance(x, int) and not isinstance(x, bool)) for x in v)
    # Iterator / NestedInteger / object / any / unknown: opaque — don't reject.
    return True


def _type_ok(v, base, dims):
    if dims == 0:
        return _scalar_ok(v, base)
    if not isinstance(v, list):
        return False
    return all(_type_ok(e, base, dims - 1) for e in v)


def validate_input(operations, args):
    if not isinstance(operations, list) or not isinstance(args, list):
        return False
    if len(operations) != len(args):
        return False
    if not operations:
        return False
    if operations[0] != _CTOR:
        return False
    for op in operations[1:]:
        if op == _CTOR or op not in _SIG:
            return False
    for op, a in zip(operations, args):
        sig = _SIG.get(op)
        if sig is None:
            return False
        if not isinstance(a, list) or len(a) != len(sig):
            return False
        for val, (base, dims) in zip(a, sig):
            if not _type_ok(val, base, dims):
                return False
    # --- value bounds from the statement (hand-added) ---
    params, lr, beta1, beta2, eps = args[0]
    d = len(params)
    if not 1 <= d <= 50 or not all(_finite(x, 100) for x in params):
        return False
    if not (_finite(lr, 1) and lr > 0):
        return False
    if not (_finite(beta1, 1) and 0 <= beta1 < 1 and _finite(beta2, 1) and 0 <= beta2 < 1):
        return False
    if not (_finite(eps, 1) and eps >= 1e-12):
        return False
    if len(operations) - 1 > 200:
        return False
    return all(len(a[0]) == d and all(_finite(x, 1000) for x in a[0]) for a in args[1:])


def _finite(x, bound):
    return math.isfinite(x) and abs(x) <= bound
